    inline const std::array<std::uint8_t, 7> &bitmap_rows(char character) {
        if (character >= 'a' && character <= 'z') {
            character = static_cast<char>(std::toupper(
                static_cast<unsigned char>(character)));
        }
        for (const auto &glyph : bitmap_glyphs) {
            if (glyph.character == character)
                return glyph.rows;
        }
        static const std::array<std::uint8_t, 7> missing = {
            0x1f, 0x11, 0x01, 0x02, 0x04, 0x00, 0x04};
        return missing;
    }

    inline void draw_bitmap_text(
        const img &target,
        const rect &clip,
        const std::string &text,
        point baseline,
        rgba color,
        int advance,
        int line_height) {
        const int top = baseline.y - line_height;
        const int y_offset = std::max(0, (line_height - 7) / 2);
        const int x_offset = std::max(0, (advance - 5) / 2);
        for (std::size_t index = 0; index < text.size(); ++index) {
            const auto &rows = bitmap_rows(text[index]);
            for (int y = 0; y < 7; ++y) {
                for (int x = 0; x < 5; ++x) {
                    if ((rows[y] & (1U << (4 - x))) == 0)
                        continue;
                    put_image_pixel(
                        target,
                        clip,
                        baseline.x + static_cast<int>(index) * advance +
                            x_offset + x,
                        top + y_offset + y,
                        color);
                }
            }
        }
    }
