#!/usr/bin/env python3
"""Render the pinned Font Awesome navigation SVGs and embed their PNG bytes.

Requires the host's librsvg, Cairo and GLib shared libraries. Production
builds use the checked-in output and have no SVG rendering dependency.
"""
import ctypes as c
import ctypes.util
from pathlib import Path
import xml.etree.ElementTree as xml

root = Path(__file__).resolve().parents[2]
assets = root / 'src/assets/navigation'
rsvg = c.CDLL(ctypes.util.find_library('rsvg-2'))
cairo = c.CDLL(ctypes.util.find_library('cairo'))
gobject = c.CDLL(ctypes.util.find_library('gobject-2.0'))
rsvg.rsvg_handle_new_from_data.argtypes = [c.c_char_p, c.c_size_t, c.c_void_p]
rsvg.rsvg_handle_new_from_data.restype = c.c_void_p
cairo.cairo_image_surface_create.argtypes = [c.c_int, c.c_int, c.c_int]
cairo.cairo_image_surface_create.restype = c.c_void_p
cairo.cairo_create.argtypes = [c.c_void_p]
cairo.cairo_create.restype = c.c_void_p
cairo.cairo_surface_write_to_png.argtypes = [c.c_void_p, c.c_char_p]
cairo.cairo_surface_write_to_png.restype = c.c_int
cairo.cairo_destroy.argtypes = [c.c_void_p]
cairo.cairo_surface_destroy.argtypes = [c.c_void_p]
gobject.g_object_unref.argtypes = [c.c_void_p]


class viewport(c.Structure):
    _fields_ = [(name, c.c_double) for name in ('x', 'y', 'width', 'height')]


rsvg.rsvg_handle_render_document.argtypes = [
    c.c_void_p, c.c_void_p, c.POINTER(viewport), c.c_void_p]
rsvg.rsvg_handle_render_document.restype = c.c_int
output = [
    '// Font Awesome Free 6.7.2 icons, Copyright 2024 Fonticons, Inc.',
    '// Derived PNGs: white glyphs on colored tiles. CC BY 4.0.',
    '// https://fontawesome.com/license/free',
    '// Generated by scripts/assets/navigation-icons.py; see README.md.',
]
for name, color in [('gear', '#6250ae'), ('calendar-days', '#b8374e'),
                    ('clock', '#176b89')]:
    source = xml.fromstring((assets / f'{name}.svg').read_bytes())
    paths = ''.join(f'<path fill="white" d="{item.attrib["d"]}"/>'
                    for item in source if 'd' in item.attrib)
    svg = (f'<svg xmlns="http://www.w3.org/2000/svg" width="32" height="32">'
           f'<rect width="32" height="32" rx="7" fill="{color}"/>'
           f'<svg x="5" y="5" width="22" height="22" '
           f'viewBox="{source.attrib["viewBox"]}">{paths}</svg></svg>').encode()
    handle = rsvg.rsvg_handle_new_from_data(svg, len(svg), None)
    if not handle:
        raise RuntimeError(f'Cannot load {name}')
    surface = cairo.cairo_image_surface_create(0, 32, 32)
    context = cairo.cairo_create(surface)
    try:
        if not rsvg.rsvg_handle_render_document(
                handle, context, c.byref(viewport(0, 0, 32, 32)), None):
            raise RuntimeError(f'Cannot render {name}')
        png = assets / f'{name}.png'
        if cairo.cairo_surface_write_to_png(surface, str(png).encode()):
            raise RuntimeError(f'Cannot save {png}')
    finally:
        cairo.cairo_destroy(context)
        cairo.cairo_surface_destroy(surface)
        gobject.g_object_unref(handle)
    output.append(f'constexpr unsigned char {name.replace("-", "_")}_png[] = {{')
    data = png.read_bytes()
    for offset in range(0, len(data), 10):
        output.append('    ' + ', '.join(f'0x{byte:02x}'
                                        for byte in data[offset:offset + 10]) + ',')
    output.append('};')
(assets / 'icons.inc').write_text('\n'.join(output) + '\n')
