#include <native/resources.h>
#include <fstream>
#include <iostream>
#include <stdexcept>

namespace
{
    // A fixed namespace keeps generated declarations portable and avoids
    // accepting arbitrary C++ identifiers in command-line input.
    void embed(const std::filesystem::path &path,
               const std::vector<std::uint8_t> &bytes) {
        std::ofstream out(path);
        if (!out) throw std::runtime_error("Cannot create embedded C++: " + path.string());
        out << "// Generated by Native rc. Do not edit.\n"
               "#include <cstdint>\n#include <span>\n\n"
               "namespace native_embedded\n{\n"
               "    std::span<const std::uint8_t> resource_data();\n"
               "    namespace\n    {\n"
               "        const std::uint8_t bytes[] = {\n            ";
        for (std::size_t i = 0; i < bytes.size(); ++i) {
            out << unsigned(bytes[i]) << ',';
            if (i % 16 == 15) out << "\n            ";
        }
        out << "\n        };\n    }\n"
               "    std::span<const std::uint8_t> resource_data() {\n"
               "        return bytes;\n    }\n}\n";
        out.close();
        if (!out) throw std::runtime_error("Cannot write embedded C++: " + path.string());
    }
    void usage(std::ostream &out) {
        out << "Usage: rc MANIFEST.json -o OUTPUT.resources [--cpp OUTPUT.cpp]\n"
               "Compiles a v1 manifest; --cpp also embeds the same pack.\n";
    }
}
int main(int argc, char **argv) {
    if (argc == 2 && std::string_view(argv[1]) == "--help") {
        usage(std::cout);
        return 0;
    }
    if ((argc != 4 && argc != 6) || std::string_view(argv[2]) != "-o" ||
        (argc == 6 && std::string_view(argv[4]) != "--cpp")) {
        usage(std::cerr);
        return 2;
    }
    try {
        const auto manifest = std::filesystem::path(argv[1]);
        const auto output = std::filesystem::path(argv[3]);
        auto canonical = [](const std::filesystem::path &path) {
            return std::filesystem::weakly_canonical(path);
        };
        if (canonical(manifest) == canonical(output) ||
            (argc == 6 && (canonical(argv[5]) == canonical(manifest) ||
                          canonical(argv[5]) == canonical(output))))
            throw std::invalid_argument("Input and output paths must differ.");
        const auto pack = native::resources::from_manifest(manifest);
        pack.save(output);
        if (argc == 6) embed(argv[5], pack.encode());
        std::cout << "Compiled " << pack.entries().size() << " variants to "
                  << output.string() << '\n';
        return 0;
    } catch (const std::exception &error) {
        std::cerr << "rc: " << error.what() << '\n';
        return 1;
    }
}
